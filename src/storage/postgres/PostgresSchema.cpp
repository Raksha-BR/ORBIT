#include "PostgresSchema.h"

#include "PostgresConnection.h"

namespace orbit {

void PostgresSchema::initialize(
    PostgresConnection& connection
) {
    connection.execute(
        R"SQL(
            CREATE TABLE IF NOT EXISTS candidate_facts (
                id BIGSERIAL PRIMARY KEY,

                fact_key TEXT NOT NULL,
                fact_value TEXT NOT NULL,

                confidence TEXT NOT NULL,

                created_at TIMESTAMPTZ NOT NULL
                    DEFAULT CURRENT_TIMESTAMP
            );

        )SQL"
    );
    connection.execute(
        R"SQL(
            CREATE TABLE IF NOT EXISTS applications (
                id BIGINT PRIMARY KEY,
                candidate_id BIGINT NOT NULL,
                job_id BIGINT NOT NULL,
                status TEXT NOT NULL,
                created_at TIMESTAMPTZ NOT NULL,
                applied_at TIMESTAMPTZ,
                last_activity_at TIMESTAMPTZ
            );
        )SQL"
    );
    
    connection.execute(
        R"SQL(
            CREATE TABLE IF NOT EXISTS jobs (
                id BIGINT PRIMARY KEY,
                title TEXT NOT NULL,
                company TEXT NOT NULL,
                location TEXT NOT NULL,
                salary TEXT,
                minimum_years_experience INTEGER,
                description TEXT NOT NULL DEFAULT '',
                application_url TEXT NOT NULL DEFAULT '',
                source_name TEXT NOT NULL DEFAULT '',
                external_job_id TEXT NOT NULL DEFAULT '',
                original_url TEXT NOT NULL DEFAULT '',
                first_seen_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                last_seen_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
            );
        )SQL"
    );

        connection.execute(
        R"SQL(
            ALTER TABLE jobs
                ADD COLUMN IF NOT EXISTS source_name TEXT NOT NULL DEFAULT '',
                ADD COLUMN IF NOT EXISTS external_job_id TEXT NOT NULL DEFAULT '',
                ADD COLUMN IF NOT EXISTS original_url TEXT NOT NULL DEFAULT '',
                ADD COLUMN IF NOT EXISTS first_seen_at
                    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                ADD COLUMN IF NOT EXISTS last_seen_at
                    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP;
        )SQL"
    );

    connection.execute(
        R"SQL(
            CREATE TABLE IF NOT EXISTS job_skills (
                job_id BIGINT NOT NULL
                    REFERENCES jobs(id) ON DELETE CASCADE,
                position INTEGER NOT NULL,
                skill TEXT NOT NULL,
                PRIMARY KEY (job_id, position)
            );
        )SQL"
    );

    connection.execute(
        R"SQL(
            CREATE TABLE IF NOT EXISTS application_events (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                application_id BIGINT NOT NULL
                    REFERENCES applications(id) ON DELETE CASCADE,
                event_type TEXT NOT NULL,
                description TEXT NOT NULL DEFAULT '',
                occurred_at TIMESTAMPTZ NOT NULL
            );
        )SQL"
    );

        connection.execute(
        R"SQL(
            CREATE INDEX IF NOT EXISTS idx_jobs_company
                ON jobs (company);

            CREATE INDEX IF NOT EXISTS idx_jobs_location
                ON jobs (location);

            CREATE INDEX IF NOT EXISTS idx_job_skills_skill
                ON job_skills (skill);

            CREATE INDEX IF NOT EXISTS idx_applications_job_id
                ON applications (job_id);
        )SQL"
    );  
}

} // namespace orbit